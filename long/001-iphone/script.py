TAIL = [("Full teardown on the channel!", S)]

def write(d, items, title):
    segs = []
    for text, o in items:
        s = {"text": text}
        if o.get('s'): s['scene'] = True
        if 'say' in o: s['say'] = o['say']
        if 'p' in o: s['pause'] = o['p']
        if 'split' in o: s['split'] = o['split']
        segs.append(s)
    os.makedirs(d, exist_ok=True)
    json.dump({"title": title, "voice": "am_puck", "speed": 0.96, "segments": segs}, open(os.path.join(d, 'episode.json'), 'w'), indent=1)

here = os.path.dirname(os.path.abspath(__file__))
for k, v in CH.items():
    write(os.path.join(here, k), v, "What's inside an iPhone? — " + k)
write(os.path.join(here, 'tail'), TAIL, 'shorts tail')
print('ok', sum(len(' '.join(t for t, _ in v).split()) for v in CH.values()), 'words')
